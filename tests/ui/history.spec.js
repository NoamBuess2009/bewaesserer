import { readFile } from 'node:fs/promises';
import { test, expect } from '@playwright/test';

test('live history records actual time, survives reload, filters and exports CSV', async ({ page, request }) => {
  await request.post('http://127.0.0.1:8080/api/stop');
  await request.put('http://127.0.0.1:8080/api/settings', { data: { times: ['07:00', '19:00'], duration_seconds: 10 } });
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Verbunden', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Jetzt bewässern' }).click();
  await expect(page.getByRole('button', { name: 'Bewässerung stoppen' })).toBeVisible();
  const running = (await (await request.get('http://127.0.0.1:8080/api/history')).json()).entries[0];
  expect(running.outcome).toBe('running');
  expect(running.actual_duration_seconds).toBeNull();
  await page.waitForTimeout(1100);
  await page.getByRole('button', { name: 'Bewässerung stoppen' }).click();
  const panel = page.locator('.history-panel');
  await expect(panel.locator('tbody tr').first()).toContainText('Manuell gestoppt');
  const stopped = (await (await request.get('http://127.0.0.1:8080/api/history')).json()).entries.find((entry) => entry.id === running.id);
  expect(stopped.actual_duration_seconds).toBeGreaterThan(1);
  expect(stopped.actual_duration_seconds).toBeLessThan(10);
  expect(stopped.planned_duration_seconds).toBe(10);
  await page.reload();
  await expect(panel.locator('tbody tr').first()).toContainText('Manuell gestoppt');
  await panel.getByRole('button', { name: '30 Tage', exact: true }).click();
  await expect(panel.locator('.history-chart-day')).toHaveCount(30);
  await panel.getByRole('button', { name: 'Manuell', exact: true }).click();
  await expect(panel.locator('tbody tr').first()).toContainText('Manuell');
  const downloadPromise = page.waitForEvent('download');
  await panel.getByRole('button', { name: 'CSV exportieren' }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toContain('30-tage.csv');
  const csv = await readFile(await download.path(), 'utf8');
  expect(csv).toContain('Tatsächliche Dauer');
  expect(csv).toContain('Gestoppt');
  expect(csv).not.toContain(';Zeitplan;');
  await panel.screenshot({ path: 'test-results/history-desktop.png' });
  await request.put('http://127.0.0.1:8080/api/settings', { data: { times: ['07:00', '19:00'], duration_seconds: 150 } });
});

test('demo history is separate, persists, and fits phone screens including 90 days', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.addInitScript(() => localStorage.setItem('gruenzeit-demo', 'true'));
  const commands = [];
  const errors = [];
  page.on('request', (request) => { if (request.method() !== 'GET' && request.url().includes('/api/')) commands.push(request.url()); });
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  const panel = page.locator('.history-panel');
  await expect(panel.getByText('Dein Protokoll beginnt mit der nächsten Bewässerung')).toBeVisible();
  await page.getByLabel('Wie lange darf’s sein?').fill('1');
  await page.getByRole('button', { name: 'Zeitplan speichern' }).click();
  await page.getByRole('button', { name: 'Jetzt bewässern' }).click();
  await expect(page.getByRole('button', { name: 'Bewässerung stoppen' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Jetzt bewässern' })).toBeVisible({ timeout: 7000 });
  await expect(panel.locator('tbody tr')).toHaveCount(1);
  await expect(panel.locator('tbody')).toContainText('Abgeschlossen');
  await page.reload();
  await expect(panel.locator('tbody tr')).toHaveCount(1);
  await expect(panel.locator('tbody')).toContainText('Abgeschlossen');
  await panel.getByRole('button', { name: '90 Tage', exact: true }).click();
  await expect(panel.locator('.history-chart-day')).toHaveCount(90);
  await expect.poll(() => panel.locator('.history-chart-scroll').evaluate((element) => element.scrollLeft)).toBeGreaterThan(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await panel.getByRole('button', { name: 'Zeitplan', exact: true }).click();
  await expect(panel.getByText('Keine passenden Durchgänge')).toBeVisible();
  await panel.getByRole('button', { name: 'Alle', exact: true }).click();
  await expect(panel.locator('tbody tr')).toHaveCount(1);
  await panel.screenshot({ path: 'test-results/history-mobile.png' });
  expect(commands).toEqual([]);
  expect(errors).toEqual([]);
});
